"""Generate docs/TOOLS.md from the live tool registry (so the reference can never drift from the code).

python scripts/gen_tool_reference.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agent.config import get_policy  # noqa: E402
from agent.tools import build_registry  # noqa: E402

TITLES = {
    "dvc": "DVC - data management",
    "mlflow": "MLflow - experiment intelligence",
    "airflow": "Airflow 3 - workflow operations",
    "kubernetes": "Kubernetes - operations",
    "insight": "Cross-system reasoning",
}
PERM = {
    "read": "read - runs immediately",
    "operate": "**operate - human approval required**",
    "mutate": "**mutate - human approval required**",
}


def _args(schema: dict) -> str:
    props = schema.get("properties", {})
    if not props:
        return "_none_"
    required = set(schema.get("required", []))
    parts = []
    for name, p in props.items():
        typ = p.get("type") or "/".join(o.get("type", "?") for o in p.get("anyOf", []))
        extra = []
        if "enum" in p:
            extra.append("one of " + ", ".join(map(str, p["enum"])))
        if "minimum" in p or "maximum" in p:
            extra.append(f"{p.get('minimum', '')}..{p.get('maximum', '')}")
        if "default" in p and p["default"] not in (None, "", {}):
            extra.append(f"default `{p['default']}`")
        flag = "" if name in required else "?"
        parts.append(f"`{name}{flag}`: {typ}" + (f" ({'; '.join(extra)})" if extra else ""))
    return "<br>".join(parts)


def main() -> None:
    reg = build_registry()
    policy = get_policy()
    lines = [
        "# Tool reference",
        "",
        "_Generated by `scripts/gen_tool_reference.py` from the live registry - do not edit by hand._",
        "",
        f"**{len(reg.names())} tools.** Every call passes through the executor (`agent/tools/base.py`): Pydantic "
        "argument validation, policy pre-checks, human-confirmation gating for operate/mutate tools, a hard timeout, "
        "error classification (`ok | error | unavailable | timeout | invalid_request | denied | requires_confirmation`) "
        "and a structured `tool_call` log record. `?` marks optional arguments.",
        "",
    ]
    for system in ("dvc", "mlflow", "airflow", "kubernetes", "insight"):
        specs = [s for s in reg.specs() if s.system == system]
        lines += [
            f"## {TITLES[system]} ({len(specs)} tools)",
            "",
            "| Tool | Permission | Arguments | Purpose |",
            "|---|---|---|---|",
        ]
        for s in specs:
            lines.append(f"| `{s.name}` | {PERM[s.permission.value]} | {_args(s.json_schema())} | {s.description} |")
        lines.append("")
    k8s, af, dvc = policy["kubernetes"], policy["airflow"], policy["dvc"]
    lines += [
        "## Policy limits (from `config/agent_policy.yaml`)",
        "",
        f"- Kubernetes namespaces (read and write): `{k8s['allowed_namespaces']}`; mutable deployments: "
        f"`{k8s['mutable_deployments']}`; replica bounds: {k8s['scale_bounds']}",
        f"- Triggerable DAGs: `{af['triggerable_dags']}`; allowed conf keys: `{af['allowed_conf_keys']}`",
        f"- DVC sub-commands: `{dvc['allowed_dvc_commands']}`; git sub-commands: `{dvc['allowed_git_commands']}`",
        f"- Confirmations expire after {policy['permissions']['confirmation_ttl_seconds']} s and are single-use, "
        "bound to the session and to a SHA-256 fingerprint of (tool, arguments).",
        "",
    ]
    out = ROOT / "docs" / "TOOLS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(reg.names())} tools)")


if __name__ == "__main__":
    main()
